//! Turn detection from the page title (#21, ADR 0021).
//!
//! Lila sets ``document.title = `${text} - ${initialTitle}` `` for the players
//! of a game, where `text` is `site.yourTurn`, `site.waitingForOpponent` or
//! `site.gameOver` in the user's lichess language. `turn_titles.json` has those
//! texts in every language lila has them. `import-lila` generates it, so don't
//! edit it by hand.

use std::collections::HashMap;
use std::sync::LazyLock;

use serde::Deserialize;

const SEPARATOR: &str = " - ";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TurnState {
    YourTurn,
    Waiting,
    GameOver,
    /// Any other title: not a game, or a spectated one.
    Other,
}

/// A state change the user should hear about.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Alert {
    YourTurn,
    GameOver,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Table {
    your_turn: Vec<String>,
    waiting_for_opponent: Vec<String>,
    game_over: Vec<String>,
}

/// Built when the first title arrives.
static STATES: LazyLock<HashMap<String, TurnState>> = LazyLock::new(|| {
    let table: Table = serde_json::from_str(include_str!("turn_titles.json"))
        .expect("turn_titles.json is generated by import-lila");
    [
        (table.your_turn, TurnState::YourTurn),
        (table.waiting_for_opponent, TurnState::Waiting),
        (table.game_over, TurnState::GameOver),
    ]
    .into_iter()
    .flat_map(|(texts, state)| texts.into_iter().map(move |text| (text, state)))
    .collect()
});

/// The state a page title stands for. The rest of the title is the page's own,
/// so it may contain the separator too.
pub fn parse(title: &str) -> TurnState {
    title
        .split_once(SEPARATOR)
        .and_then(|(text, _)| STATES.get(text).copied())
        .unwrap_or(TurnState::Other)
}

/// Turns the states of the shown game into alerts, at most one per change.
#[derive(Debug, Default)]
pub struct Detector {
    /// The game shown last and its state. Other titles don't reset it, because
    /// reloading a game goes through the title of the loading page, and that
    /// is no change of the game's state.
    last: Option<(String, TurnState)>,
}

impl Detector {
    /// Takes the state of `game`, which identifies the game (its URL). A
    /// change while `focused` is remembered without an alert. A game first seen
    /// as over ended before we looked at it, as when opening an old game, so
    /// only a game seen running can give a game-over alert.
    pub fn observe(&mut self, game: &str, state: TurnState, focused: bool) -> Option<Alert> {
        if state == TurnState::Other {
            return None;
        }
        let previous = self
            .last
            .as_ref()
            .filter(|(last_game, _)| last_game == game)
            .map(|(_, last_state)| *last_state);
        if previous == Some(state) {
            return None;
        }
        self.last = Some((game.to_owned(), state));
        let alert = match (state, previous) {
            (TurnState::YourTurn, _) => Some(Alert::YourTurn),
            (TurnState::GameOver, Some(_)) => Some(Alert::GameOver),
            _ => None,
        };
        alert.filter(|_| !focused)
    }
}

/// Whether the tray icon should show that it's the user's turn: while the page
/// says so and the window isn't focused. Unlike an alert this is a lasting
/// state, so a turn that began while focused shows once the user leaves.
#[derive(Debug, Default)]
pub struct Badge {
    your_turn: bool,
    shown: bool,
}

impl Badge {
    /// Takes the page's new state, if it has one, and the current focus.
    /// Returns the new value when it changes, so the icon is only set then.
    pub fn update(&mut self, state: Option<TurnState>, focused: bool) -> Option<bool> {
        if let Some(state) = state {
            self.your_turn = state == TurnState::YourTurn;
        }
        let show = self.your_turn && !focused;
        (show != self.shown).then(|| {
            self.shown = show;
            show
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use TurnState::{GameOver, Other, Waiting, YourTurn};

    const GAME: &str = "https://lichess.org/abcd1234efgh";
    const OTHER_GAME: &str = "https://lichess.org/zyxw9876vuts";
    const UNFOCUSED: bool = false;
    const FOCUSED: bool = true;

    #[test]
    fn parses_real_titles_in_several_languages() {
        for (title, state) in [
            ("Your turn - Play anonymous on lichess.org", YourTurn),
            ("Waiting for opponent - lichess.org", Waiting),
            ("Game Over - lichess.org", GameOver),
            ("Du bist am Zug - Lichess", YourTurn),
            ("あなたの手番です - lichess.org", YourTurn),
            // Right to left: the text still comes first in logical order.
            ("دورك - lichess.org", YourTurn),
            ("תורך - lichess.org", YourTurn),
        ] {
            assert_eq!(parse(title), state, "{title}");
        }
    }

    #[test]
    fn the_page_part_of_a_title_may_contain_the_separator() {
        assert_eq!(parse("Your turn - Alice - Bob - lichess.org"), YourTurn);
    }

    #[test]
    fn unknown_titles_are_other() {
        for title in [
            "",
            "lichess.org",
            "Your turn",
            "Your turn-lichess.org",
            "your turn - lichess.org",
            "Not your turn - lichess.org",
            "lichess.org - Your turn",
            "Bob - Your turn - lichess.org",
        ] {
            assert_eq!(parse(title), Other, "{title:?}");
        }
    }

    #[test]
    fn the_table_is_complete_and_no_text_is_lost_to_a_clash() {
        let table: Table = serde_json::from_str(include_str!("turn_titles.json")).unwrap();
        let total =
            table.your_turn.len() + table.waiting_for_opponent.len() + table.game_over.len();
        assert_eq!(STATES.len(), total);
        for text in ["Your turn", "Waiting for opponent", "Game Over"] {
            assert!(STATES.contains_key(text), "{text} is missing");
        }
    }

    #[test]
    fn alerts_once_per_state_change() {
        let mut detector = Detector::default();
        assert_eq!(detector.observe(GAME, Waiting, UNFOCUSED), None);
        assert_eq!(
            detector.observe(GAME, YourTurn, UNFOCUSED),
            Some(Alert::YourTurn)
        );
        assert_eq!(detector.observe(GAME, YourTurn, UNFOCUSED), None);
        assert_eq!(detector.observe(GAME, Waiting, UNFOCUSED), None);
        assert_eq!(
            detector.observe(GAME, YourTurn, UNFOCUSED),
            Some(Alert::YourTurn)
        );
        assert_eq!(
            detector.observe(GAME, GameOver, UNFOCUSED),
            Some(Alert::GameOver)
        );
        assert_eq!(detector.observe(GAME, GameOver, UNFOCUSED), None);
    }

    #[test]
    fn never_alerts_while_focused() {
        let mut detector = Detector::default();
        assert_eq!(detector.observe(GAME, YourTurn, FOCUSED), None);
        assert_eq!(detector.observe(GAME, Waiting, FOCUSED), None);
        assert_eq!(detector.observe(GAME, GameOver, FOCUSED), None);
    }

    #[test]
    fn a_change_seen_while_focused_gives_no_alert_after_leaving() {
        let mut detector = Detector::default();
        assert_eq!(detector.observe(GAME, YourTurn, FOCUSED), None);
        assert_eq!(detector.observe(GAME, YourTurn, UNFOCUSED), None);
    }

    #[test]
    fn reloading_a_game_is_not_a_change() {
        let mut detector = Detector::default();
        detector.observe(GAME, YourTurn, UNFOCUSED);
        assert_eq!(detector.observe(GAME, Other, UNFOCUSED), None);
        assert_eq!(detector.observe(GAME, YourTurn, UNFOCUSED), None);
    }

    #[test]
    fn other_titles_never_alert() {
        let mut detector = Detector::default();
        assert_eq!(detector.observe(GAME, Other, UNFOCUSED), None);
    }

    #[test]
    fn a_game_first_seen_as_over_gives_no_alert() {
        let mut detector = Detector::default();
        assert_eq!(detector.observe(GAME, GameOver, UNFOCUSED), None);

        detector.observe(GAME, Waiting, UNFOCUSED);
        assert_eq!(detector.observe(OTHER_GAME, GameOver, UNFOCUSED), None);
    }

    #[test]
    fn the_badge_shows_during_your_turn_while_unfocused() {
        let mut badge = Badge::default();
        assert_eq!(badge.update(Some(Waiting), UNFOCUSED), None);
        assert_eq!(badge.update(Some(YourTurn), UNFOCUSED), Some(true));
        assert_eq!(badge.update(Some(YourTurn), UNFOCUSED), None);
        assert_eq!(badge.update(Some(Waiting), UNFOCUSED), Some(false));
    }

    #[test]
    fn the_badge_follows_the_focus() {
        let mut badge = Badge::default();
        assert_eq!(badge.update(Some(YourTurn), FOCUSED), None);
        assert_eq!(badge.update(None, UNFOCUSED), Some(true));
        assert_eq!(badge.update(None, FOCUSED), Some(false));
        assert_eq!(badge.update(None, FOCUSED), None);
    }

    #[test]
    fn the_badge_goes_away_when_the_turn_does() {
        for state in [GameOver, Other] {
            let mut badge = Badge::default();
            badge.update(Some(YourTurn), UNFOCUSED);
            assert_eq!(badge.update(Some(state), UNFOCUSED), Some(false));
        }
    }

    #[test]
    fn a_new_game_in_the_same_state_is_a_change() {
        let mut detector = Detector::default();
        detector.observe(GAME, YourTurn, UNFOCUSED);
        assert_eq!(
            detector.observe(OTHER_GAME, YourTurn, UNFOCUSED),
            Some(Alert::YourTurn)
        );
    }
}
